// Bundles widget/map3d.ts (three.js included) into one script string for the ChatGPT widget,
// which can't load scripts from other origins. Runs before `next dev` / `next build`.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = await build({
  entryPoints: [resolve(root, "widget/map3d.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2020",
  write: false,
  legalComments: "none",
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
writeFileSync(
  resolve(root, "lib/widget-bundle.generated.ts"),
  `// Generated by scripts/build-widget.mjs from widget/map3d.ts. Do not edit.\nexport const WIDGET_JS = ${JSON.stringify(js)};\n`
);
console.log(`widget bundle: ${(js.length / 1024).toFixed(0)} KB`);
